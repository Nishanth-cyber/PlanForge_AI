import React from 'react';
import type { RefinementResult } from '../../api/types';

interface RefinementViewProps {
  refinementResult?: RefinementResult | null;
}

export const RefinementView: React.FC<RefinementViewProps> = ({ refinementResult }) => {
  if (!refinementResult || !refinementResult.iterations || refinementResult.iterations.length === 0) {
    return (
      <div className="card" style={{ textAlign: 'center', padding: '3.5rem' }}>
        <div style={{ fontSize: '2rem', marginBottom: '0.5rem' }}>✓</div>
        <h3 style={{ fontSize: '1.2rem', fontWeight: 600, color: 'var(--text-primary)', marginBottom: '0.4rem' }}>
          No Refinement Was Required
        </h3>
        <p style={{ color: 'var(--text-secondary)', maxWidth: '500px', margin: '0 auto', fontSize: '0.875rem' }}>
          Initial physical geometry generated by the Architectural LLM and Geometry Engine passed all authoritative
          validator checks on the first pass without triggering the closed-loop correction agent.
        </p>
      </div>
    );
  }

  const iterations = refinementResult.iterations;
  const initErrors = iterations[0]?.error_count || 0;
  const finalErrors = iterations[iterations.length - 1]?.error_count || 0;
  const errorDelta = Math.max(0, initErrors - finalErrors);

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '2rem' }}>
      {/* Summary Card */}
      <div className="card">
        <div className="card-header">
          <div>
            <h2 className="card-title">Closed-Loop Validation-Driven Refinement</h2>
            <p className="card-subtitle">
              Iterative correction loop driven by independent validator feedback while preserving immutable upstream ASAA allocations.
            </p>
          </div>
          <span className={`badge ${refinementResult.is_valid ? 'badge-success' : 'badge-warning'}`}>
            {refinementResult.status.replace(/_/g, ' ')}
          </span>
        </div>

        <div className="grid grid-cols-4 gap-4" style={{ marginTop: '0.5rem' }}>
          <div className="property-row" style={{ flexDirection: 'column', alignItems: 'flex-start' }}>
            <span className="property-label">Iterations Attempted</span>
            <span className="property-value" style={{ fontSize: '1.25rem' }}>
              {iterations.length}
            </span>
          </div>

          <div className="property-row" style={{ flexDirection: 'column', alignItems: 'flex-start' }}>
            <span className="property-label">Initial Hard Errors</span>
            <span className="property-value" style={{ fontSize: '1.25rem', color: 'var(--text-primary)' }}>
              {initErrors}
            </span>
          </div>

          <div className="property-row" style={{ flexDirection: 'column', alignItems: 'flex-start' }}>
            <span className="property-label">Final Hard Errors</span>
            <span className="property-value" style={{ fontSize: '1.25rem', color: 'var(--text-primary)' }}>
              {finalErrors}
            </span>
          </div>

          <div className="property-row" style={{ flexDirection: 'column', alignItems: 'flex-start' }}>
            <span className="property-label">Hard Errors Resolved</span>
            <span className="property-value" style={{ fontSize: '1.25rem', color: 'var(--text-primary)' }}>
              +{errorDelta}
            </span>
          </div>
        </div>
      </div>

      {/* Iteration Timeline Cards */}
      <div style={{ display: 'flex', flexDirection: 'column', gap: '1.25rem' }}>
        {iterations.map((it, idx) => (
          <div key={idx} className="card" style={{ borderLeft: '4px solid var(--border-strong)' }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '0.75rem' }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                <span className="badge badge-neutral" style={{ fontSize: '0.75rem' }}>
                  Iteration {it.iteration}
                </span>
                <strong style={{ fontSize: '1rem', color: 'var(--text-primary)' }}>
                  {idx === 0 ? 'Initial Architectural Proposal' : `Refinement Pass ${it.iteration}`}
                </strong>
              </div>

              <div style={{ display: 'flex', gap: '0.75rem', fontSize: '0.8rem' }}>
                <span style={{ color: 'var(--text-secondary)' }}>
                  <strong>{it.error_count}</strong> Errors
                </span>
                <span style={{ color: 'var(--text-muted)' }}>
                  <strong>{it.warning_count}</strong> Warnings
                </span>
                <span className={`badge ${it.overall_valid ? 'badge-success' : 'badge-danger'}`}>
                  {it.overall_valid ? 'Valid' : 'Invalid'}
                </span>
              </div>
            </div>

            {/* Changes list in this iteration */}
            {it.changes && it.changes.length > 0 ? (
              <div style={{ marginTop: '0.75rem' }}>
                <span style={{ fontSize: '0.75rem', fontWeight: 600, color: 'var(--text-muted)', textTransform: 'uppercase', display: 'block', marginBottom: '0.4rem' }}>
                  Architectural Adjustments Applied ({it.changes.length})
                </span>
                <div style={{ display: 'flex', flexDirection: 'column', gap: '0.35rem' }}>
                  {it.changes.map((ch, ci) => (
                    <div
                      key={ch.id || ci}
                      style={{
                        padding: '0.55rem 0.75rem',
                        background: 'var(--bg-secondary)',
                        borderRadius: 'var(--radius-sm)',
                        fontSize: '0.8rem',
                        display: 'flex',
                        flexDirection: 'column',
                        gap: '0.2rem',
                      }}
                    >
                      <div style={{ display: 'flex', justifyContent: 'space-between', color: 'var(--accent-sky)' }}>
                        <strong>{ch.room_id || 'Room'} • {ch.field_changed}</strong>
                        <span style={{ color: 'var(--text-muted)' }}>Floor {ch.floor_number}</span>
                      </div>
                      <span style={{ color: 'var(--text-secondary)' }}>{ch.reason}</span>
                    </div>
                  ))}
                </div>
              </div>
            ) : (
              <p style={{ fontSize: '0.8rem', color: 'var(--text-muted)', fontStyle: 'italic', marginTop: '0.4rem' }}>
                {idx === 0 ? 'Baseline geometric construction from ASAA allocated bounding regions.' : 'No discrete changes applied in this step.'}
              </p>
            )}
          </div>
        ))}
      </div>
    </div>
  );
};
